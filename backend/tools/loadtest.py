"""NYAYA SETU load test: 50,000 complaint cases.

What it does
  1. Builds a SEPARATE database (default: sqlite:///./loadtest.db) so the demo data is untouched.
  2. Seeds the normal demo (bureaus, users, 18 fictional institutions, scenarios).
  3. Adds N_INST extra fictional institutions and N_CASES synthetic complaint cases
     (bulk insert), with realistic spreads of bureau, status, category, region and dates.
  4. Starts the real API and times the endpoints an officer actually uses.

DATA HONESTY
  Every case created here is SYNTHETIC test data, generated by this script with a fixed
  random seed so the run is reproducible. Real AICTE complaint records are confidential
  personal data and are not publicly available; they are never used or imitated here.
  Institutions are fictional ("Demo Institute of Technology 0001" ...) so no real college
  is associated with an invented complaint.

Run:  python tools/loadtest.py            (N_CASES=50000 by default)
"""
import os
import random
import statistics
import subprocess
import sys
import time
from datetime import datetime, timedelta, timezone

N_CASES = int(os.environ.get("N_CASES", 50000))
N_INST = int(os.environ.get("N_INST", 3000))
DB_URL = os.environ.get("LOADTEST_DB", "sqlite:///./loadtest.db")
PORT = int(os.environ.get("LOADTEST_PORT", 8765))
SEED = 26264

os.environ["DATABASE_URL"] = DB_URL
os.environ["ALERT_SCAN_ENABLED"] = "false"
os.environ.setdefault("CACHE_WARMUP", "false")  # measure the cold first call honestly
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def build() -> None:
    if DB_URL.startswith("sqlite:///./") and os.path.exists(DB_URL[len("sqlite:///./"):]):
        os.remove(DB_URL[len("sqlite:///./"):])
    t0 = time.time()
    subprocess.run([sys.executable, "seed.py", "--reset"], check=True, stdout=subprocess.DEVNULL)
    from sqlalchemy import insert
    from app.data.registry import REGIONS
    from app.db.session import SessionLocal
    from app.models.bureau import Bureau
    from app.models.case import Case, CaseAction, CasePriority, CaseStatus
    from app.models.institution import Institution, InstitutionIdentifier
    from app.models.user import User, UserRole

    rnd = random.Random(SEED)
    db = SessionLocal()
    now = datetime.now(timezone.utc)
    bureaus = {b.code: b.id for b in db.query(Bureau).all()}
    officers = {}
    for u in db.query(User).filter(User.role == UserRole.BUREAU_OFFICER).all():
        officers.setdefault(u.bureau_id, []).append(u.id)
    states = {"Northern": ["Uttar Pradesh", "Uttarakhand", "Bihar"], "North-West": ["Haryana", "Punjab", "Delhi", "Rajasthan"],
              "Central": ["Madhya Pradesh", "Chhattisgarh", "Gujarat"], "Eastern": ["West Bengal", "Odisha", "Jharkhand", "Assam"],
              "Western": ["Maharashtra", "Goa"], "Southern": ["Tamil Nadu", "Puducherry"], "South-West": ["Karnataka", "Kerala"],
              "South-Central": ["Telangana", "Andhra Pradesh"]}
    kinds = ["Institute of Technology", "College of Engineering", "Institute of Management", "College of Pharmacy", "Polytechnic"]

    # institutions
    inst_rows, ident_rows = [], []
    base_id = db.query(Institution).count()
    for k in range(N_INST):
        region = REGIONS[k % len(REGIONS)]
        inst_rows.append(dict(
            canonical_name=f"Demo {kinds[k % len(kinds)]} {k + 1:04d}", short_name=f"DIT{k + 1:04d}",
            institution_type=rnd.choice(["Private Unaided", "Government", "Government Aided", "Deemed University"]),
            state=rnd.choice(states[region]), city=f"City {k % 400 + 1}", region=region,
            data_source="loadtest_synthetic", import_notes="SYNTHETIC load-test institution", created_at=now))
    db.execute(insert(Institution), inst_rows)
    db.commit()
    inst_ids = [i for (i,) in db.query(Institution.id).order_by(Institution.id).all()][base_id:]
    for n, iid in enumerate(inst_ids):
        ident_rows.append(dict(institution_id=iid, id_type="aicte_permanent_id", id_value=f"9-{9000000000 + n}",
                               source_system="loadtest (synthetic)", is_primary=True, is_verified=False, created_at=now))
    db.execute(insert(InstitutionIdentifier), ident_rows)
    db.commit()

    # cases: bureau share, status share and timelines are assumptions for testing, not AICTE statistics
    bureau_w = [("PGRC", 40), ("RB", 25), ("AB", 15), ("ACAD", 10), ("FIN", 10)]
    status_w = [(CaseStatus.DISPOSED, 45), (CaseStatus.CLOSED, 10), (CaseStatus.UNDER_PROCESS, 15), (CaseStatus.ASSIGNED, 8),
                (CaseStatus.RECEIVED, 6), (CaseStatus.AWAITING_INFORMATION, 5), (CaseStatus.TRANSFERRED, 4),
                (CaseStatus.ESCALATED, 3), (CaseStatus.DECISION_REVIEW, 2), (CaseStatus.REOPENED, 2)]
    sla = {"PGRC": 30, "RB": 60, "AB": 45, "ACAD": 45, "FIN": 30}
    cats = ["Fee Refund", "Fee Regulation", "Infrastructure", "Faculty Shortage", "Admission Irregularity",
            "Scholarship", "Certificate / Degree", "Ragging / Safety", "Approval Conditions", "Examination"]
    # 20% of institutions attract most complaints (skewed, as complaints usually are)
    hot = inst_ids[: max(1, len(inst_ids) // 5)]
    pick_b = [c for c, w in bureau_w for _ in range(w)]
    pick_s = [s for s, w in status_w for _ in range(w)]
    pick_open = [s for s in pick_s if s not in (CaseStatus.DISPOSED, CaseStatus.CLOSED, CaseStatus.TRANSFERRED)]
    year = now.year
    start_no = db.query(Case).count()
    BATCH = 5000
    for b0 in range(0, N_CASES, BATCH):
        rows = []
        for n in range(b0, min(N_CASES, b0 + BATCH)):
            code = rnd.choice(pick_b)
            rec = now - timedelta(days=rnd.uniform(0, 730))
            age = (now - rec).days
            # Assumption for the test: older files are mostly closed, recent ones mostly open
            if age > 2 * sla[code] and rnd.random() < 0.93:
                st = rnd.choice([CaseStatus.DISPOSED] * 4 + [CaseStatus.CLOSED, CaseStatus.TRANSFERRED])
            elif age <= sla[code]:
                st = rnd.choice(pick_open)
            else:
                st = rnd.choice(pick_s)
            due = rec + timedelta(days=sla[code])
            off = officers.get(bureaus[code], [None])
            rows.append(dict(
                case_number=f"AICTE-LT-{year}-{start_no + n + 1:06d}", source_system="loadtest (synthetic)",
                institution_id=rnd.choice(hot) if rnd.random() < 0.6 else rnd.choice(inst_ids),
                bureau_id=bureaus[code], assigned_officer_id=rnd.choice(off),
                title=f"[Synthetic] {rnd.choice(cats)} complaint #{n + 1}", category=rnd.choice(cats),
                status=st, priority=rnd.choice(list(CasePriority)), received_date=rec, due_date=due,
                disposed_date=(rec + timedelta(days=rnd.uniform(5, sla[code] * 1.5))) if st in (CaseStatus.DISPOSED, CaseStatus.CLOSED) else None,
                last_action_date=rec + timedelta(days=rnd.uniform(0, 20)), is_active=True, created_at=rec))
        db.execute(insert(Case), rows)
        db.commit()
    new_ids = [i for (i,) in db.query(Case.id).filter(Case.source_system == "loadtest (synthetic)").all()]
    acts = []
    for cid in new_ids:
        acts.append(dict(case_id=cid, action_type="created", description="Complaint received (synthetic)", created_at=now))
    for a0 in range(0, len(acts), 20000):
        db.execute(insert(CaseAction), acts[a0:a0 + 20000])
        db.commit()
    total = db.query(Case).count()
    db.close()
    print(f"Built {total:,} cases across {N_INST + 18:,} institutions in {time.time() - t0:.1f}s ({DB_URL})")


def measure() -> list:
    import httpx
    env = dict(os.environ)
    proc = subprocess.Popen([sys.executable, "-m", "uvicorn", "app.main:app", "--port", str(PORT)],
                            env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    base = f"http://127.0.0.1:{PORT}/api/v1"
    try:
        for _ in range(60):
            try:
                if httpx.get(base + "/health", timeout=2).status_code == 200:
                    break
            except Exception:
                time.sleep(0.5)
        from app.core.security import create_access_token
        from app.db.session import SessionLocal
        from app.models.user import User
        db = SessionLocal()
        mgmt = db.query(User).filter(User.email == "management@aicte.demo").first()
        off = db.query(User).filter(User.email == "officer2@aicte.demo").first()
        db.close()
        H = {"Authorization": "Bearer " + create_access_token({"sub": str(mgmt.id)})}
        HO = {"Authorization": "Bearer " + create_access_token({"sub": str(off.id)})}
        c = httpx.Client(timeout=300)
        tests = [
            ("Case list, page 1 (25 rows)", "GET", "/cases/?limit=25", H, 10),
            ("Case list, search by text", "GET", "/cases/?limit=25&search=Fee", H, 10),
            ("Case list, filters (bureau+status+region)", "GET", "/cases/?limit=25&bureau_id=2&status=under_process&region=Southern", H, 10),
            ("Case list, overdue only", "GET", "/cases/?limit=25&overdue=true", H, 5),
            ("Case detail", "GET", "/cases/1", H, 10),
            ("Command Centre overview", "GET", "/analytics/overview", H, 5),
            ("Monthly performance (12 months)", "GET", "/analytics/performance?period=monthly", H, 5),
            ("Region-wise report", "GET", "/analytics/regions", H, 5),
            ("Institution 360", "GET", "/intelligence/institutions/1/360", H, 5),
            ("Overlap Radar (all institutions)", "GET", "/intelligence/overlaps", H, 3),
            ("Risk Radar (all institutions)", "GET", "/intelligence/risk", H, 3),
            ("Identify college from text (IRE)", "POST", "/intelligence/resolve", H, 10),
            ("PGRC officer: own case list", "GET", "/cases/?limit=25", HO, 10),
            ("Export all cases CSV (50k rows)", "GET", "/reports/cases/csv", H, 2),
            ("Case register PDF (first 1,000 rows)", "GET", "/reports/cases/pdf", H, 2),
        ]
        results = []
        for name, method, path, hdr, n in tests:
            times, code = [], None
            for _ in range(n):
                t = time.perf_counter()
                if method == "GET":
                    r = c.get(base + path, headers=hdr)
                else:
                    r = c.post(base + path, headers=hdr, json={"text": "Students of A.I.E.T. Faridabad are charged extra fees"})
                times.append((time.perf_counter() - t) * 1000)
                code = r.status_code
            results.append((name, code, times[0], statistics.median(times[1:]) if len(times) > 1 else times[0]))
        # write path: register a complaint (includes overlap check)
        times = []
        for k in range(5):
            t = time.perf_counter()
            r = c.post(base + "/cases/", headers=H, json={"title": f"Load-test registration {k}", "category": "Fee Refund",
                                                          "institution_id": 1, "bureau_id": 2})
            times.append((time.perf_counter() - t) * 1000)
        results.append(("Register complaint (+ overlap check)", r.status_code, times[0], statistics.median(times[1:])))
        # after a write, the radar recomputes only the changed institution
        t = time.perf_counter()
        r = c.get(base + "/intelligence/overlaps", headers=H)
        ms = (time.perf_counter() - t) * 1000
        results.append(("Overlap Radar right after a new complaint", r.status_code, ms, ms))
        return results
    finally:
        proc.terminate()


if __name__ == "__main__":
    if "--measure-only" not in sys.argv:
        build()
    res = measure()
    print(f"\n{'Endpoint':45s} {'HTTP':>4s} {'first call ms':>14s} {'repeat (median) ms':>19s}")
    for name, code, first, rep in res:
        print(f"{name:45s} {code:>4d} {first:14.0f} {rep:19.0f}")
